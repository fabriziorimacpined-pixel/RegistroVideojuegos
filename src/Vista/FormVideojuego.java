    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
String titulo = txtNombre.getText().trim();

    if (titulo.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "No puede registrar un videojuego sin título."
        );
        txtNombre.requestFocus();
        return;
    }

    String genero = cboGenero.getSelectedItem().toString();
    double precio = Double.parseDouble(txtPrecio.getText());

    Videojuego videojuego = new Videojuego(titulo, genero, precio);

    listaVideojuegos.add(videojuego);

    int cantidad = listaVideojuegos.size();

    lblContador.setText("Cantidad de videojuegos registrados: " + cantidad);

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tablaVideojuegos.getModel();

    modelo.addRow(new Object[]{
        videojuego.getTitulo(),
        videojuego.getGenero(),
        String.format("S/ %.2f", videojuego.getPrecio())
    });

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Videojuego registrado correctamente.\nCantidad de videojuegos: " + cantidad
    );

    txtNombre.setText("");
    txtPrecio.setText("");
    txtNombre.requestFocus();


    }//GEN-LAST:event_btnAgregarActionPerformed

