    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
int fila = tablaVideojuegos.getSelectedRow();

    if (fila == -1) {
        javax.swing.JOptionPane.showMessageDialog(
            this,
            "Seleccione un videojuego de la tabla."
        );
        return;
    }

    listaVideojuegos.remove(fila);

    int cantidad = listaVideojuegos.size();

    lblContador.setText("Cantidad de videojuegos registrados: " + cantidad);

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tablaVideojuegos.getModel();

    modelo.removeRow(fila);

    javax.swing.JOptionPane.showMessageDialog(
        this,
        "Videojuego eliminado correctamente.\nCantidad de videojuegos: " + cantidad
    );


    }//GEN-LAST:event_btnEliminarActionPerformed


